#!/usr/bin/env node
// Plans moving registered repositories and their linked worktrees out of a
// TCC-protected folder. It only reads git state and writes migrate/verify/
// rollback scripts into a new directory; a human runs them after confirmation.
import { mkdir, realpath, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { cliOptions, contains, execute, isMain, readJson, requireUnprotectedRoot, requireValue, runCli, writeJson } from "./ilv2-mac-contracts.mjs";

const quote = value => `'${String(value).replaceAll("'", "'\\''")}'`;
const exists = target => stat(target).then(() => true, () => false);

export function parseWorktrees(porcelain) {
  return porcelain.split("\n\n").filter(Boolean).map(block => {
    const row = { locked: false, prunable: false, bare: false, detached: false };
    for (const line of block.split("\n")) {
      const [key, ...rest] = line.split(" ");
      const value = rest.join(" ");
      if (key === "worktree") row.path = value;
      else if (key === "HEAD") row.head = value;
      else if (key === "branch") row.branch = value;
      else if (key in row) row[key] = true;
    }
    return row;
  });
}

async function repoPlan(root, fromRoot, toRoot, git) {
  const real = await realpath(root);
  requireValue(contains(fromRoot, real) && real !== fromRoot, `${real} is not inside ${fromRoot}`);
  const [main, ...linked] = parseWorktrees((await git(["-C", real, "worktree", "list", "--porcelain"])).stdout);
  requireValue(main.path === real && !main.bare, `${real} is not a non-bare main worktree`);
  const target = source => path.join(toRoot, path.relative(fromRoot, source));
  const moves = [], external = [], prunable = [], blockers = [];
  for (const row of linked) {
    if (row.prunable) { prunable.push(row.path); continue; }
    // Worktrees nested in the main checkout move with it and only need repair.
    if (contains(fromRoot, row.path) && !contains(real, row.path)) moves.push({ from: row.path, to: target(row.path), locked: row.locked });
    else external.push({ path: row.path, movesWithMain: contains(real, row.path), after: contains(real, row.path) ? target(row.path) : row.path });
  }
  for (const move of [{ from: real, to: target(real) }, ...moves])
    if (await exists(move.to)) blockers.push(`target exists: ${move.to}`);
  return { root: real, to: target(real), branch: main.branch ?? null, head: main.head, moves, external, prunable: prunable.length, blockers };
}

function scripts(plan) {
  const migrate = ["#!/bin/sh", "# Generated by scripts/ilv2-mac-worktree-migration.mjs; review before running.", "set -eu",
    // A process whose cwd is inside a moved tree (an editor, agent or build) must stop first.
    `/usr/sbin/lsof -d cwd -Fn 2>/dev/null | sed -n 's/^n//p' | awk 'NR == FNR { roots[$0] = 1; next } { for (root in roots) if (index($0 "/", root) == 1) { print "busy: " $0 > "/dev/stderr"; busy = 1 } } END { exit busy ? 2 : 0 }' ${quote(path.join(plan.out, "moved-roots.txt"))} -`];
  const rollback = ["#!/bin/sh", "# Reverses migrate.sh; run only after verify.sh failed or the move must be undone.", "set -eu"];
  const verify = ["#!/bin/sh", "set -eu", "fail=0"];
  for (const repo of plan.repos) {
    migrate.push("", `# ${repo.root}`);
    for (const move of [{ from: repo.root, to: repo.to }, ...repo.moves])
      migrate.push(`test ! -e ${quote(move.to)}`, `mkdir -p ${quote(path.dirname(move.to))}`, `mv ${quote(move.from)} ${quote(move.to)}`);
    // Repair from the moved main with every moved linked path re-links both directions.
    migrate.push(`git -C ${quote(repo.to)} worktree repair ${repo.moves.map(move => quote(move.to)).join(" ")}`.trimEnd());
    rollback.push("", `# ${repo.root}`);
    for (const move of [...repo.moves].reverse()) rollback.push(`mv ${quote(move.to)} ${quote(move.from)}`);
    rollback.push(`mv ${quote(repo.to)} ${quote(repo.root)}`, `git -C ${quote(repo.root)} worktree repair ${repo.moves.map(move => quote(move.from)).join(" ")}`.trimEnd());
    verify.push("", `# ${repo.root}`,
      `test "$(git -C ${quote(repo.to)} worktree list --porcelain | grep -c '^prunable')" = ${repo.prunable} || { echo "prunable count changed: ${repo.to}" >&2; fail=1; }`);
    for (const target of [repo.to, ...repo.moves.map(move => move.to), ...repo.external.map(row => row.after)])
      verify.push(`test "$(git -C ${quote(target)} rev-parse --show-toplevel 2>/dev/null)" = ${quote(target)} || { echo "broken: ${target}" >&2; fail=1; }`);
  }
  verify.push("exit $fail");
  return { migrate: `${migrate.join("\n")}\n`, rollback: `${rollback.join("\n")}\n`, verify: `${verify.join("\n")}\n` };
}

export async function planMigration({ roots, fromRoot, toRoot, out, git = args => execute("git", ["--no-optional-locks", ...args], { maxBuffer: 64 * 1024 * 1024 }) }) {
  fromRoot = await realpath(fromRoot);
  requireValue(path.isAbsolute(toRoot) && !contains(fromRoot, toRoot) && !contains(toRoot, fromRoot), "target root must be absolute and disjoint from the source root");
  requireUnprotectedRoot(toRoot, "migration target");
  requireUnprotectedRoot(out, "migration plan output");
  requireValue(!(await exists(out)), `plan output already exists: ${out}`);
  const repos = [];
  for (const root of roots) repos.push(await repoPlan(root, fromRoot, toRoot, git));
  const plan = { schema: "ilv2-worktree-migration-plan/v1", fromRoot, toRoot, out, createdAt: new Date().toISOString(), repos,
    totals: { mains: repos.length, linkedMoves: repos.reduce((sum, repo) => sum + repo.moves.length, 0),
      externalRepairs: repos.reduce((sum, repo) => sum + repo.external.length, 0), prunableUntouched: repos.reduce((sum, repo) => sum + repo.prunable, 0) },
    blockers: repos.flatMap(repo => repo.blockers) };
  // Moving a parent first would make the nested source vanish half-way through migrate.sh.
  const sources = repos.flatMap(repo => [repo.root, ...repo.moves.map(move => move.from)]);
  for (const inner of sources) for (const outer of sources)
    if (inner !== outer && contains(outer, inner)) plan.blockers.push(`nested move source: ${inner} is inside ${outer}`);
  await mkdir(out, { recursive: true, mode: 0o700 });
  const text = scripts(plan);
  await writeFile(path.join(out, "moved-roots.txt"), `${repos.flatMap(repo => [repo.root, ...repo.moves.map(move => move.from)]).map(root => `${root}/`).join("\n")}\n`);
  for (const [name, body] of Object.entries(text)) await writeFile(path.join(out, `${name}.sh`), body, { mode: 0o700 });
  await writeJson(path.join(out, "plan.json"), plan);
  return plan;
}

export async function rootsFromProjects(file) {
  const config = await readJson(file);
  return config.aliases.map(alias => alias.root);
}

if (isMain(import.meta.url)) runCli(async () => {
  const options = cliOptions(process.argv.slice(2), ["--projects", "--from", "--to", "--out"]);
  requireValue(options.projects && options.from && options.to && options.out, "usage: --projects F --from DIR --to DIR --out NEW_DIR");
  const plan = await planMigration({ roots: await rootsFromProjects(options.projects), fromRoot: options.from, toRoot: options.to, out: options.out });
  console.log(JSON.stringify({ out: plan.out, totals: plan.totals, blockers: plan.blockers }, null, 2));
  process.exitCode = plan.blockers.length ? 1 : 0;
});
