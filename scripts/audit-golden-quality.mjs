#!/usr/bin/env node
// input: Frozen golden jsonl + optional pin tree / commit-task index. Tuning only.
// output: Per-scene NOISY labels and GOLDEN_NOISY | GOLDEN_TRUSTED. Holdout rows are dropped unread.
// pos: A1. Six pre-registered rules. Does not retune. Does not touch src/.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const A1_SCHEMA = "a-a1-audit/v1";
export const A1_NOISY_GATE = 0.3;
export const A1_CONTROL_SAMPLE = 10;
export const NOISY_RULE_IDS = Object.freeze([
  "mustHitGt8",
  "testInMustHit",
  "codegenShareGe50",
  "modulesGe4",
  "anchorOutsideDepNeighborhood",
  "mergeOrDiffGt30"
]);

const GENERATOR_HEADER_RE = /@generated|generated by|auto-generated|do not (edit|modify)|codegen/i;
const YUDAO_DO_RE = /(?:^|\/)[^/]*-do\/[^/]*DO\.java$/i;
const YUDAO_DATAOBJECT_RE = /\/dal\/dataobject\/[^/]*DO\.java$/i;

export function posixPath(relative) {
  return String(relative ?? "").replaceAll("\\", "/");
}

export function isHoldoutScene(row) {
  if (row?.evaluationSplit === "holdout") return true;
  if (row?.evaluationSplit === "tuning") return false;
  return /holdout/i.test(String(row?.id ?? ""));
}

export function loadTuningScenes(jsonlText) {
  const tuning = [];
  let holdoutSkipped = 0;
  for (const line of String(jsonlText ?? "").split(/\r?\n/)) {
    if (!line.trim()) continue;
    const row = JSON.parse(line);
    if (isHoldoutScene(row)) {
      holdoutSkipped += 1;
      continue;
    }
    tuning.push(row);
  }
  return { tuning, holdoutSkipped };
}

export function isTestPath(relative) {
  const normalized = posixPath(relative);
  const base = normalized.split("/").pop() ?? "";
  return normalized.includes("/src/test/") || /Test\.java$/.test(base);
}

export function mavenModuleOf(relative, moduleRoots = []) {
  const normalized = posixPath(relative);
  const roots = [...moduleRoots].filter(Boolean).sort((left, right) => right.length - left.length);
  for (const root of roots) {
    if (normalized === root || normalized.startsWith(`${root}/`)) return root;
  }
  const parts = normalized.split("/").filter(Boolean);
  if ((parts[0] === "modules" || parts[0] === "apps") && parts[1]) return `${parts[0]}/${parts[1]}`;
  return parts[0] || "";
}

export function isYudaoEntityDo(relative) {
  const normalized = posixPath(relative);
  return YUDAO_DO_RE.test(normalized) || YUDAO_DATAOBJECT_RE.test(normalized);
}

export function batchTemplatePaths(changedFiles) {
  const groups = new Map();
  for (const file of changedFiles ?? []) {
    const normalized = posixPath(file);
    if (!normalized || isYudaoEntityDo(normalized)) continue;
    const slash = normalized.lastIndexOf("/");
    const dir = slash >= 0 ? normalized.slice(0, slash) : "";
    const base = slash >= 0 ? normalized.slice(slash + 1) : normalized;
    const dot = base.lastIndexOf(".");
    const suffix = dot >= 0 ? base.slice(dot) : "";
    const key = `${dir}\0${suffix}`;
    const bucket = groups.get(key) ?? [];
    bucket.push(normalized);
    groups.set(key, bucket);
  }
  const batch = new Set();
  for (const bucket of groups.values()) {
    if (bucket.length >= 5) for (const file of bucket) batch.add(file);
  }
  return batch;
}

export function headerLooksGenerated(text) {
  const head = String(text ?? "").split(/\r?\n/).slice(0, 40).join("\n");
  return GENERATOR_HEADER_RE.test(head);
}

export function isCodegenPath(relative, { batchPaths = new Set(), generatedHeaders = new Set() } = {}) {
  const normalized = posixPath(relative);
  if (normalized.includes("/codegen/")) return true;
  if (generatedHeaders.has(normalized)) return true;
  if (batchPaths.has(normalized)) return true;
  return false;
}

export function inspectCommitMeta(sha, { git } = {}) {
  const run = git ?? ((args) => {
    throw new Error(`git not provided: ${args.join(" ")}`);
  });
  if (!sha) return { sha: null, isMerge: false, changedFileCount: null, degraded: true };
  try {
    const parents = String(run(["log", "-1", "--format=%P", sha]) ?? "").trim().split(/\s+/).filter(Boolean);
    const isMerge = parents.length > 1;
    let changedFileCount = null;
    if (parents.length >= 1) {
      const names = String(run(["diff", "--name-only", `${sha}^`, sha]) ?? "")
        .split(/\r?\n/)
        .map(line => line.trim())
        .filter(Boolean);
      changedFileCount = names.length;
    }
    return { sha, isMerge, changedFileCount, degraded: false, parents };
  } catch {
    return { sha, isMerge: false, changedFileCount: null, degraded: true };
  }
}

export function auditMustHit(mustHit, context = {}) {
  const files = [...new Set((mustHit ?? []).map(posixPath).filter(Boolean))];
  const reasons = [];
  if (files.length > 8) reasons.push("mustHitGt8");
  if (files.some(isTestPath)) reasons.push("testInMustHit");

  const codegenHits = files.filter(file => isCodegenPath(file, context));
  if (files.length > 0 && codegenHits.length / files.length >= 0.5) reasons.push("codegenShareGe50");

  const modules = [...new Set(files.map(file => mavenModuleOf(file, context.moduleRoots)))].filter(Boolean);
  if (modules.length >= 4) reasons.push("modulesGe4");

  const anchor = posixPath(context.anchorFile);
  if (anchor) {
    const neighborhood = new Set();
    const deps = context.moduleDeps ?? {};
    for (const mod of modules) {
      neighborhood.add(mod);
      for (const dep of deps[mod] ?? []) neighborhood.add(dep);
    }
    const anchorModule = mavenModuleOf(anchor, context.moduleRoots);
    if (anchorModule && !neighborhood.has(anchorModule)) reasons.push("anchorOutsideDepNeighborhood");
  }

  const isMerge = context.isMerge === true;
  const changed = context.changedFileCount;
  if (isMerge || (Number.isInteger(changed) && changed > 30)) reasons.push("mergeOrDiffGt30");

  return {
    noisy: reasons.length > 0,
    reasons,
    mustHitCount: files.length,
    moduleCount: modules.length,
    codegenShare: files.length ? codegenHits.length / files.length : 0
  };
}

export function auditTuningScene(scene, context = {}) {
  const mustHit = scene?.golden?.mustHit ?? [];
  const labeled = auditMustHit(mustHit, {
    ...context,
    anchorFile: scene?.anchor?.file ?? context.anchorFile
  });
  return {
    scenarioId: scene?.id,
    noisy: labeled.noisy,
    reasons: labeled.reasons,
    mustHitCount: labeled.mustHitCount,
    moduleCount: labeled.moduleCount,
    codegenShare: labeled.codegenShare
  };
}

export function sampleTuningScenes(scenes, n = A1_CONTROL_SAMPLE) {
  const ordered = [...(scenes ?? [])].sort((left, right) => String(left.id).localeCompare(String(right.id)));
  return ordered.slice(0, Math.max(0, n));
}

export function noisyRate(labels) {
  const n = labels?.length ?? 0;
  if (n === 0) return null;
  return labels.filter(row => row.noisy).length / n;
}

export function decideGoldenQuality({ ruoyiNoisyRate, controlNoisyRates } = {}) {
  const controls = (controlNoisyRates ?? []).filter(value => typeof value === "number");
  const controlMean = controls.length ? controls.reduce((sum, value) => sum + value, 0) / controls.length : null;
  const ruleTooStrict = controlMean != null && controlMean >= A1_NOISY_GATE;
  const threshold = ruleTooStrict ? controlMean * 2 : A1_NOISY_GATE;
  if (ruoyiNoisyRate == null) {
    return { decision: "UNMEASURED", ruleTooStrict, threshold, controlMean, ruoyiNoisyRate: null };
  }
  const decision = ruoyiNoisyRate >= threshold ? "GOLDEN_NOISY" : "GOLDEN_TRUSTED";
  return { decision, ruleTooStrict, threshold, controlMean, ruoyiNoisyRate };
}

export function indexCommitTasks(payload) {
  const index = new Map();
  for (const task of [...(payload?.train ?? []), ...(payload?.holdout ?? [])]) {
    if (!task?.commit) continue;
    index.set(task.commit, task);
    index.set(String(task.commit).slice(0, 16), task);
  }
  return index;
}

export function sceneSourceCommit(scene, commitIndex) {
  if (scene?.sourceCommit) return scene.sourceCommit;
  const id = String(scene?.id ?? "");
  const prefix = `${scene?.projectId ?? ""}-`;
  const suffix = prefix && id.startsWith(prefix) ? id.slice(prefix.length) : id;
  const task = commitIndex?.get(suffix) ?? commitIndex?.get(scene?.repoCommit);
  return task?.commit ?? suffix;
}

export function listMavenModuleRoots(repoRoot) {
  if (!repoRoot || !existsSync(repoRoot)) return [];
  const roots = [];
  const walk = (dir, rel) => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    const hasPom = entries.some(entry => entry.isFile() && entry.name === "pom.xml");
    if (hasPom && rel) roots.push(rel);
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;
      if (entry.name === ".git" || entry.name === "node_modules" || entry.name === "target" || entry.name === "yudao-ui") continue;
      walk(path.join(dir, entry.name), rel ? `${rel}/${entry.name}` : entry.name);
    }
  };
  walk(repoRoot, "");
  return roots;
}

export function parsePomDependencies(pomText) {
  const artifact = String(pomText ?? "").match(/<artifactId>\s*([^<]+)\s*<\/artifactId>/);
  const deps = [];
  const block = String(pomText ?? "").match(/<dependencies>([\s\S]*?)<\/dependencies>/);
  if (block) {
    for (const match of block[1].matchAll(/<artifactId>\s*([^<]+)\s*<\/artifactId>/g)) {
      const name = match[1].trim();
      if (name) deps.push(name);
    }
  }
  return { artifactId: artifact?.[1]?.trim() || null, deps };
}

export function loadModuleDepGraph(repoRoot, moduleRoots) {
  const deps = {};
  for (const rel of moduleRoots ?? []) {
    const pom = path.join(repoRoot, rel, "pom.xml");
    if (!existsSync(pom)) continue;
    const parsed = parsePomDependencies(readFileSync(pom, "utf8"));
    const key = parsed.artifactId || rel;
    deps[rel] = parsed.deps;
    if (key !== rel) deps[key] = parsed.deps;
  }
  return deps;
}

export function gitRunner(repoRoot) {
  return (args) => execFileSync("git", ["-C", repoRoot, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

export function buildA1RepoContext(repoRoot) {
  const moduleRoots = listMavenModuleRoots(repoRoot);
  const moduleDeps = loadModuleDepGraph(repoRoot, moduleRoots);
  const git = repoRoot && existsSync(path.join(repoRoot, ".git")) ? gitRunner(repoRoot) : null;
  return {
    moduleRoots,
    moduleDeps,
    contextForTask(task) {
      const commitFiles = (task?.files ?? []).map(file => file.path);
      let meta = {
        isMerge: false,
        changedFileCount: commitFiles.length || null,
        degraded: !git
      };
      if (git && task?.commit) {
        meta = inspectCommitMeta(task.commit, { git });
        if (meta.degraded && commitFiles.length) meta = { ...meta, changedFileCount: commitFiles.length };
      }
      const generatedHeaders = new Set();
      for (const file of commitFiles) {
        if (headerLooksGenerated(readHeader(repoRoot, file))) generatedHeaders.add(posixPath(file));
      }
      return {
        moduleRoots,
        moduleDeps,
        batchPaths: batchTemplatePaths(commitFiles),
        generatedHeaders,
        isMerge: meta.isMerge,
        changedFileCount: meta.changedFileCount
      };
    }
  };
}

function readHeader(repoRoot, relative) {
  if (!repoRoot) return "";
  const full = path.join(repoRoot, relative);
  if (!existsSync(full) || !statSync(full).isFile()) return "";
  try {
    return readFileSync(full, "utf8").slice(0, 4000);
  } catch {
    return "";
  }
}

export function auditProject({
  projectId,
  jsonlText,
  repoRoot,
  commitIndex,
  sample,
  git
} = {}) {
  const loaded = loadTuningScenes(jsonlText);
  const scenes = sample ? sampleTuningScenes(loaded.tuning, sample) : loaded.tuning;
  const moduleRoots = listMavenModuleRoots(repoRoot);
  const moduleDeps = loadModuleDepGraph(repoRoot, moduleRoots);
  const runGit = git ?? (repoRoot && existsSync(path.join(repoRoot, ".git")) ? gitRunner(repoRoot) : null);
  const labels = [];
  let degraded = 0;
  for (const scene of scenes) {
    const sourceCommit = sceneSourceCommit(scene, commitIndex);
    const task = commitIndex?.get(sourceCommit) ?? commitIndex?.get(String(sourceCommit).slice(0, 16));
    const commitFiles = (task?.files ?? []).map(file => file.path);
    let meta = { isMerge: false, changedFileCount: commitFiles.length || null, degraded: !runGit };
    if (runGit && sourceCommit) {
      meta = inspectCommitMeta(sourceCommit, { git: runGit });
      if (meta.degraded && Number.isInteger(commitFiles.length)) {
        meta = { ...meta, changedFileCount: commitFiles.length };
      }
    } else if (task?.parent && Array.isArray(task.files)) {
      meta = { sha: sourceCommit, isMerge: false, changedFileCount: task.files.length, degraded: true };
    }
    if (meta.degraded) degraded += 1;
    const batchPaths = batchTemplatePaths(commitFiles.length ? commitFiles : (scene.golden?.mustHit ?? []));
    const generatedHeaders = new Set();
    for (const file of scene.golden?.mustHit ?? []) {
      if (headerLooksGenerated(readHeader(repoRoot, file))) generatedHeaders.add(posixPath(file));
    }
    const labeled = auditTuningScene(scene, {
      moduleRoots,
      moduleDeps,
      batchPaths,
      generatedHeaders,
      isMerge: meta.isMerge,
      changedFileCount: meta.changedFileCount
    });
    labels.push({ ...labeled, sourceCommit, commitMetaDegraded: meta.degraded === true });
  }
  return {
    projectId,
    holdoutSkipped: loaded.holdoutSkipped,
    tuning: loaded.tuning.length,
    audited: labels.length,
    noisyRate: noisyRate(labels),
    degradedCommits: degraded,
    scenes: labels
  };
}

function parseCli(args) {
  const options = new Map();
  for (let index = 0; index < args.length; index += 1) {
    const key = args[index];
    if (key === "--help") return { help: true };
    if (!key.startsWith("--") || index + 1 >= args.length) throw new Error(`invalid argument: ${key}`);
    options.set(key, args[++index]);
  }
  return {
    ruoyiJsonl: options.get("--ruoyi-jsonl"),
    ruoyiRoot: options.get("--ruoyi-root"),
    commitTasks: options.get("--commit-tasks"),
    lishueduJsonl: options.get("--lishuedu-jsonl"),
    cipherlinkJsonl: options.get("--cipherlink-jsonl"),
    examJsonl: options.get("--exam-parent-v3-jsonl"),
    lishueduRoot: options.get("--lishuedu-root"),
    cipherlinkRoot: options.get("--cipherlink-root"),
    examRoot: options.get("--exam-parent-v3-root"),
    output: options.get("--output"),
    controlSample: options.get("--control-sample") ? Number(options.get("--control-sample")) : A1_CONTROL_SAMPLE
  };
}

function readOptional(file) {
  return file && existsSync(file) ? readFileSync(file, "utf8") : null;
}

export function runA1Audit(cli) {
  const commitPayload = cli.commitTasks && existsSync(cli.commitTasks)
    ? JSON.parse(readFileSync(cli.commitTasks, "utf8"))
    : {};
  const commitIndex = indexCommitTasks(commitPayload);
  const ruoyiText = readFileSync(cli.ruoyiJsonl, "utf8");
  const ruoyi = auditProject({
    projectId: "ruoyi-vue-pro",
    jsonlText: ruoyiText,
    repoRoot: cli.ruoyiRoot,
    commitIndex
  });
  const controls = [];
  const controlSpecs = [
    ["lishuedu", cli.lishueduJsonl, cli.lishueduRoot],
    ["cipherlink", cli.cipherlinkJsonl, cli.cipherlinkRoot],
    ["exam-parent-v3", cli.examJsonl, cli.examRoot]
  ];
  for (const [projectId, jsonl, repoRoot] of controlSpecs) {
    const text = readOptional(jsonl);
    if (!text) {
      controls.push({ projectId, noisyRate: null, audited: 0, note: "missing jsonl" });
      continue;
    }
    controls.push(auditProject({
      projectId,
      jsonlText: text,
      repoRoot,
      sample: cli.controlSample
    }));
  }
  const verdict = decideGoldenQuality({
    ruoyiNoisyRate: ruoyi.noisyRate,
    controlNoisyRates: controls.map(row => row.noisyRate).filter(value => typeof value === "number")
  });
  const pinMissing = !cli.ruoyiRoot || !existsSync(cli.ruoyiRoot);
  const status = pinMissing ? "AUDIT_DEGRADED" : verdict.ruleTooStrict ? "RULE_TOO_STRICT" : verdict.decision;
  return {
    schemaVersion: A1_SCHEMA,
    dated: "2026-08-24",
    status,
    decision: verdict.decision,
    ruleTooStrict: verdict.ruleTooStrict,
    threshold: verdict.threshold,
    gate: A1_NOISY_GATE,
    rules: [...NOISY_RULE_IDS],
    ruoyi,
    control: controls,
    verdict,
    pin: {
      root: cli.ruoyiRoot ?? null,
      present: Boolean(cli.ruoyiRoot && existsSync(cli.ruoyiRoot))
    },
    note: "Holdout scenes skipped. Six NOISY rules are pre-registered. Do not retune from holdout."
  };
}

function main(argv = process.argv.slice(2)) {
  const cli = parseCli(argv);
  if (cli.help) {
    console.log("usage: node scripts/audit-golden-quality.mjs --ruoyi-jsonl <jsonl> --ruoyi-root <pin> --output <json>");
    return;
  }
  if (!cli.ruoyiJsonl || !cli.output) throw new Error("--ruoyi-jsonl and --output are required");
  const report = runA1Audit(cli);
  writeFileSync(cli.output, `${JSON.stringify(report, null, 2)}\n`);
  console.log(JSON.stringify({
    output: cli.output,
    decision: report.decision,
    status: report.status,
    ruoyiNoisyRate: report.ruoyi.noisyRate,
    holdoutSkipped: report.ruoyi.holdoutSkipped
  }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
