const MODULE_ROOTS = [
  "yudao-module-mes",
  "yudao-module-system",
  "yudao-module-infra",
  "yudao-module-wms",
  "yudao-framework"
];

function scene(id, mustHit, extra = {}) {
  return {
    id,
    evaluationSplit: extra.evaluationSplit ?? "tuning",
    anchor: { file: extra.anchor ?? mustHit[0] },
    golden: { mustHit }
  };
}

test("six NOISY rules are frozen", () => {
  assert.deepEqual([...NOISY_RULE_IDS], [
    "mustHitGt8",
    "testInMustHit",
    "codegenShareGe50",
    "modulesGe4",
    "anchorOutsideDepNeighborhood",
    "mergeOrDiffGt30"
  ]);
  assert.equal(A1_NOISY_GATE, 0.3);
});

test("mustHitGt8 positive and negative", () => {
  const files = Array.from({ length: 9 }, (_, index) => `yudao-module-mes/src/main/java/A${index}.java`);
  const pos = auditMustHit(files, { moduleRoots: MODULE_ROOTS, anchorFile: files[0] });
  assert.equal(pos.reasons.includes("mustHitGt8"), true);
  const neg = auditMustHit(files.slice(0, 8), { moduleRoots: MODULE_ROOTS, anchorFile: files[0] });
  assert.equal(neg.reasons.includes("mustHitGt8"), false);
});

