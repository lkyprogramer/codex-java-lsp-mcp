test("codegenShareGe50 positive and negative", () => {
  const codegenDir = [
    "yudao-module-infra/src/main/java/codegen/A.java",
    "yudao-module-infra/src/main/java/codegen/B.java",
    "yudao-module-infra/src/main/java/service/C.java"
  ];
  const posPath = auditMustHit(codegenDir, {
    moduleRoots: MODULE_ROOTS,
    anchorFile: codegenDir[2]
  });
  assert.equal(isCodegenPath("yudao-module-infra/src/main/java/codegen/A.java"), true);
  assert.equal(posPath.reasons.includes("codegenShareGe50"), true);

  const sameDir = [
    "yudao-module-mes/src/main/java/vo/A.java",
    "yudao-module-mes/src/main/java/vo/B.java",
    "yudao-module-mes/src/main/java/vo/C.java",
    "yudao-module-mes/src/main/java/vo/D.java",
    "yudao-module-mes/src/main/java/vo/E.java"
  ];
  const batch = batchTemplatePaths(sameDir);
  assert.equal(batch.size, 5);
  const posBatch = auditMustHit(sameDir.slice(0, 4), {
    moduleRoots: MODULE_ROOTS,
    anchorFile: sameDir[0],
    batchPaths: batch
  });
  assert.equal(posBatch.reasons.includes("codegenShareGe50"), true);

  const entityDo = [
    "yudao-module-mes/src/main/java/dal/dataobject/FooDO.java",
    "yudao-module-mes/src/main/java/dal/dataobject/BarDO.java",
    "yudao-module-mes/src/main/java/dal/dataobject/BazDO.java",
    "yudao-module-mes/src/main/java/dal/dataobject/QuxDO.java",
    "yudao-module-mes/src/main/java/dal/dataobject/NorfDO.java"
  ];
  const doBatch = batchTemplatePaths(entityDo);
  assert.equal(doBatch.size, 0);
  const negDo = auditMustHit(entityDo, {
    moduleRoots: MODULE_ROOTS,
    anchorFile: entityDo[0],
    batchPaths: doBatch
  });
  assert.equal(negDo.reasons.includes("codegenShareGe50"), false);

  assert.equal(headerLooksGenerated("/* Generated by MyBatis Plus Generator */\npackage x;\n"), true);
  const headerPos = auditMustHit(
    ["yudao-module-mes/src/main/java/A.java", "yudao-module-mes/src/main/java/B.java"],
    {
      moduleRoots: MODULE_ROOTS,
      anchorFile: "yudao-module-mes/src/main/java/A.java",
      generatedHeaders: new Set(["yudao-module-mes/src/main/java/A.java"])
    }
  );
  assert.equal(headerPos.reasons.includes("codegenShareGe50"), true);

  const four = sameDir.slice(0, 4);
  const tooSmall = batchTemplatePaths(four);
  assert.equal(tooSmall.size, 0);
  const neg = auditMustHit(four, {
    moduleRoots: MODULE_ROOTS,
    anchorFile: four[0],
    batchPaths: tooSmall
  });
  assert.equal(neg.reasons.includes("codegenShareGe50"), false);
});

